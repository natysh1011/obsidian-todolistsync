import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repository = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const translateDirectory = resolve(repository, "translate");
const locales = [
  "af", "am", "ar", "az", "be", "bg", "bn", "ca", "cs", "da", "de",
  "dv", "el", "en-GB", "en", "eo", "es", "eu", "fa", "fi", "fr",
  "ga", "gl", "he", "hi", "hr", "hu", "id", "it", "ja", "ka", "kab",
  "kh", "kn", "ko", "ky", "la", "lt", "lv", "ml", "ms", "nan-TW",
  "ne", "nl", "nn", "no", "oc", "or", "pl", "pt-BR", "pt", "ro", "ru",
  "sa", "si", "sk", "sl", "sq", "sr", "sv", "sw", "ta", "te", "th",
  "tl", "tr", "tt", "uk", "ur", "uz", "vi", "zh-TW", "zh",
];
const activeLocales = new Set(["en", "he"]);
const rtlLocales = new Set(["ar", "dv", "fa", "he", "ur"]);
const identifierAliases = {
  "en-GB": "enGB",
  "nan-TW": "nanTW",
  "pt-BR": "ptBR",
  "zh-TW": "zhTW",
};

const englishPath = resolve(translateDirectory, "en.json");
const english = JSON.parse(await readFile(englishPath, "utf8"));
const hash = createHash("sha256")
  .update(JSON.stringify(english.messages))
  .digest("hex");

for (const locale of locales) {
  const path = resolve(translateDirectory, `${locale}.json`);
  const available = activeLocales.has(locale);
  let messages = {};
  if (available) {
    const existing = JSON.parse(await readFile(path, "utf8"));
    messages = existing.messages;
  }
  const payload = {
    _meta: {
      locale,
      sourceHash: hash,
      direction: rtlLocales.has(locale) ? "rtl" : "ltr",
      available,
    },
    messages,
  };
  await writeFile(path, `${JSON.stringify(payload, null, 2)}\n`);
}

const imports = locales.map((locale) => {
  const identifier = identifierAliases[locale] ?? locale.replaceAll("-", "");
  return `import ${identifier} from "../translate/${locale}.json";`;
});
const entries = locales.map((locale) => {
  const identifier = identifierAliases[locale] ?? locale.replaceAll("-", "");
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(locale)
    ? `  ${locale}: ${identifier},`
    : `  "${locale}": ${identifier},`;
});
const catalog = [
  "// Generated by scripts/generate-locales.mjs. Do not edit manually.",
  ...imports,
  "",
  `export const LOCALE_CODES = ${JSON.stringify(locales)} as const;`,
  `export const AVAILABLE_LOCALE_CODES = ${JSON.stringify([...activeLocales])} as const;`,
  "",
  "export const TRANSLATION_CATALOG = {",
  ...entries,
  "} as const;",
  "",
].join("\n");
await writeFile(resolve(repository, "src/locale-catalog.ts"), catalog);
process.stdout.write(`Generated ${locales.length} locale files (${activeLocales.size} available).\n`);
