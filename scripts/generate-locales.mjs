import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { localeCodes, localeDefinitions } from "./locale-registry.mjs";

const repository = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const translateDirectory = resolve(repository, "translate");
const locales = localeCodes;
const activeLocales = new Set(localeCodes);
const availableLocaleCodes = localeCodes;
const definitionsByCode = new Map(
  localeDefinitions.map((definition) => [definition.code, definition]),
);
const identifierAliases = {
  "en-GB": "enGB",
  "nan-TW": "nanTW",
  "pt-BR": "ptBR",
  "zh-TW": "zhTW",
};

const englishPath = resolve(translateDirectory, "en.json");
const english = JSON.parse(await readFile(englishPath, "utf8"));
const hash = createHash("sha256")
  .update(JSON.stringify(english.messages))
  .digest("hex");

for (const locale of locales) {
  const definition = definitionsByCode.get(locale);
  if (!definition) throw new Error(`Missing locale definition for ${locale}`);
  const path = resolve(translateDirectory, `${locale}.json`);
  const available = activeLocales.has(locale);
  const existing = JSON.parse(await readFile(path, "utf8"));
  const messages = existing.messages;
  const payload = {
    _meta: {
      locale,
      nativeName: definition.nativeName,
      sourceHash: hash,
      direction: definition.direction,
      available,
    },
    messages,
  };
  await writeFile(path, `${JSON.stringify(payload, null, 2)}\n`);
}

const imports = locales.map((locale) => {
  const identifier = identifierAliases[locale] ?? locale.replaceAll("-", "");
  return `import ${identifier} from "../translate/${locale}.json";`;
});
const entries = locales.map((locale) => {
  const identifier = identifierAliases[locale] ?? locale.replaceAll("-", "");
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(locale)
    ? `  ${locale}: ${identifier},`
    : `  "${locale}": ${identifier},`;
});
const catalog = [
  "// Generated by scripts/generate-locales.mjs. Do not edit manually.",
  ...imports,
  "",
  `export const LOCALE_CODES = ${JSON.stringify(locales)} as const;`,
  `export const AVAILABLE_LOCALE_CODES = ${JSON.stringify(availableLocaleCodes)} as const;`,
  `export const NATIVE_LOCALE_NAMES = ${JSON.stringify(Object.fromEntries(localeDefinitions.map(({ code, nativeName }) => [code, nativeName])))} as const;`,
  "",
  "export const TRANSLATION_CATALOG = {",
  ...entries,
  "} as const;",
  "",
].join("\n");
await writeFile(resolve(repository, "src/locale-catalog.ts"), catalog);
process.stdout.write(`Generated ${locales.length} locale files (${activeLocales.size} available).\n`);
